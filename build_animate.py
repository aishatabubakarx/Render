#!/usr/bin/env python3
"""Bake every animate.css animation into animate_kf.js by sampling REAL Chromium CSS animations (exact easing, no re-implementation).
CSS animations run on wall-clock time, which a seek-per-frame renderer cannot use; baking gives ANI(name, p) for any p in 0..1.
  python build_animate.py            (needs playwright + chromium; the generated animate_kf.js is shipped in the kit)
Per sample: opacity, 2D matrix a b c d, translate in px and in % of element size (found by sampling 100px and 200px boxes).
3D flips/perspective are projected to 2D (rotateX/Y become a squash on that axis)."""
import json, os, re
from playwright.sync_api import sync_playwright
HERE = os.path.dirname(os.path.abspath(__file__)); N = 60
css = open(os.path.join(HERE, 'vendor', 'animate.css'), encoding='utf-8').read()
names = sorted(set(re.findall(r'@keyframes\s+([\w-]+)', css)))
JS = """([name,N])=>{const out=[];
 for(const size of [100,200]){document.body.innerHTML='';const row=[];
  for(let i=0;i<=N;i++){const e=document.createElement('div');e.className='animate__animated animate__'+name;e.style.cssText=`width:${size}px;height:${size}px;position:absolute;animation-duration:1s;animation-fill-mode:both;animation-play-state:paused;animation-delay:-${i/N}s`;document.body.appendChild(e);const cs=getComputedStyle(e);const m=new DOMMatrix(cs.transform==='none'?undefined:cs.transform);
   row.push([+cs.opacity,m.m11,m.m12,m.m21,m.m22,m.m41,m.m42]);e.remove()}
  out.push(row)}return out}"""
out = {}
with sync_playwright() as p:
    b = p.chromium.launch(args=['--disable-gpu']); pg = b.new_page()
    pg.set_content('<style>' + css + '</style><body></body>')
    for n in names:
        a100, a200 = pg.evaluate(JS, [n, N]); rows = []
        for r1, r2 in zip(a100, a200):
            pxx = r2[5] - r1[5]; pxy = r2[6] - r1[6]          # change per +100px of box size = percent part *100
            txp, typ = pxx, pxy                                  # percent of size, expressed as % (since +100px == +100%/100)
            tx = r1[5] - txp; ty = r1[6] - typ                   # leftover = px part
            rows.append([round(v, 4) for v in (r1[0], r1[1], r1[2], r1[3], r1[4], tx, ty, txp, typ)])
        out[n] = rows
    b.close()
js = '/* generated by build_animate.py: animate.css 4.1.1 (MIT) baked from real Chromium animations, 61 samples each */\nconst ANIKF=' + json.dumps(out, separators=(',', ':')) + ';\n'
js += r'''/* ANI('bounceIn', p) -> {o,a,b,c,d,tx,ty,txp,typ} at p in 0..1 (linear between the 61 baked samples).
   Any animate.css name works: bounceIn, fadeInUp, zoomOut, flipInX, backInLeft, rubberBand, tada, ... (list: Object.keys(ANIKF)) */
function ANI(name,p){const k=ANIKF[name];if(!k)throw new Error('unknown animate.css animation '+name);p=Math.max(0,Math.min(1,p))*(k.length-1);
  const i=Math.min(Math.floor(p),k.length-2),u=p-i,A=k[i],B=k[i+1],r=[];for(let j=0;j<9;j++)r.push(A[j]+(B[j]-A[j])*u);
  return {o:r[0],a:r[1],b:r[2],c:r[3],d:r[4],tx:r[5],ty:r[6],txp:r[7],typ:r[8]}}
/* withANI(state, cx, cy, w, h, fn): apply the animation's transform around (cx,cy) (percent translates use w,h), set alpha, run fn() drawing centered on 0,0 */
function withANI(s,cx,cy,w,h,fn){ctx.save();ctx.translate(cx+s.tx+s.txp/100*w,cy+s.ty+s.typ/100*h);ctx.transform(s.a,s.b,s.c,s.d,0,0);
  ctx.globalAlpha*=Math.max(0,Math.min(1,s.o));fn();ctx.restore()}
'''
open(os.path.join(HERE, 'animate_kf.js'), 'w').write(js)
print(len(out), 'animations baked,', len(js) // 1024, 'KB')
